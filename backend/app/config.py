from functools import lru_cache
from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8", extra="ignore")

    data_dir: Path = Path("D:/Sermons")
    secret_key: str = "change-me"  # overridden from .env; generated by scripts/setup.ps1
    session_days: int = 14
    cookie_secure: bool = False  # LAN over plain http

    ollama_url: str = "http://127.0.0.1:11434"
    llm_model: str = "qwen2.5:7b-instruct"
    embed_model: str = "nomic-embed-text"
    llm_num_ctx: int = 8192

    whisper_model: str = "large-v3-turbo"
    whisper_device: str = "auto"  # auto | cuda | cpu
    whisper_compute_type: str = "int8_float16"

    ffmpeg: str = "ffmpeg"
    ffprobe: str = "ffprobe"
    video_encoder: str = "auto"  # auto | h264_nvenc | libx264

    max_upload_gb: float = 20.0
    max_duration_hours: float = 6.0
    # Only the first account can self-register; after that the owner adds people on the Team page.
    allow_registration: bool = False
    upload_chunk_mb: int = 16

    @property
    def db_path(self) -> Path:
        return self.data_dir / "db" / "app.db"

    @property
    def media_dir(self) -> Path:
        return self.data_dir / "media"

    models_dir: Path | None = None  # defaults to <data_dir>/models

    @property
    def whisper_dir(self) -> Path:
        return (self.models_dir or self.data_dir / "models") / "whisper"


@lru_cache
def get_settings() -> Settings:
    s = Settings()
    for p in (s.db_path.parent, s.media_dir, s.whisper_dir, s.media_dir / "_uploads"):
        p.mkdir(parents=True, exist_ok=True)
    return s
