def _eval(expr: str, W=1080, H=1920, w=200, h=50) -> float:
    return eval(expr, {}, {"W": W, "H": H, "w": w, "h": h})  # expressions are generated by us, not user input


def test_overlay_positions_spread_evenly():
    assert wm.overlay_xy("r0c0", 40) == "40:40"
    assert wm.overlay_xy("r5c2", 40) == "W-w-40:H-h-40"
    assert wm.overlay_xy("r0c1", 40).startswith("(W-w)/2:")
    assert len({wm.overlay_xy(p, 40) for p in wm.POSITIONS}) == 18
    ys = [_eval(wm.overlay_xy(f"r{r}c0", 40).split(":")[1]) for r in range(6)]
    gaps = [b - a for a, b in zip(ys, ys[1:])]
    assert ys[0] == 40 and ys[-1] == 1920 - 50 - 40
    assert max(gaps) - min(gaps) < 1e-6  # evenly spaced rows
    xs = [_eval(wm.overlay_xy(f"r2c{c}", 40).split(":")[0]) for c in range(3)]
    assert xs == [40, (1080 - 200) / 2, 1080 - 200 - 40]


def test_watermark_moves_off_the_logo():
    assert wm.avoid_overlap_dy("r0c2", "r0c2", logo_h=170, margin=43) == 170 + 21  # top half: push down
    assert wm.avoid_overlap_dy("r5c0", "r5c0", logo_h=170, margin=43) == -(170 + 21)  # bottom half: push up
    assert wm.avoid_overlap_dy("r0c0", "r0c2", logo_h=170, margin=43) == 0  # different cells: no change
    assert wm.avoid_overlap_dy("r0c2", "top-right", logo_h=170, margin=43) != 0  # old name for the same cell
    assert wm.overlay_xy("r0c2", 40, 191) == "W-w-40:40+191"


def test_image_scales_with_size_and_opacity():
    small = wm.build_image(wm.clamp_spec(text="@church", icons=["youtube"], size=50), 1080, 1920)
    big = wm.build_image(wm.clamp_spec(text="@church", icons=["youtube"], size=200), 1080, 1920)
    assert big.height > small.height * 3 and big.width > small.width * 3
    faint = wm.build_image(wm.clamp_spec(text="@church", opacity=20), 1080, 1920)
    solid = wm.build_image(wm.clamp_spec(text="@church", opacity=100), 1080, 1920)
    assert faint.getchannel("A").getextrema()[1] < solid.getchannel("A").getextrema()[1]
    for name in wm.SOCIAL_ICONS:
        assert wm.draw_icon(name, 40).getbbox() is not None  # every icon draws something


def test_brand_kit_watermark_api(client):
    client.post("/api/auth/register", json={"email": "p@example.com", "password": "password123", "name": "P"})
    k = client.get("/api/brand-kits").json()[0]
    assert (k["watermark_position"], k["logo_position"], k["watermark_size"], k["social_icons"]) == \
        ("r0c0", "r0c2", 100, [])
    r = client.patch(f"/api/brand-kits/{k['id']}", json={"watermark_text": "@grace", "watermark_position": "r4c1",
                                                         "logo_position": "r3c0", "watermark_size": 150,
                                                         "watermark_opacity": 60, "social_icons": ["tiktok", "instagram"]})
    assert r.status_code == 200, r.text
    k = r.json()
    assert (k["watermark_position"], k["logo_position"], k["watermark_size"], k["watermark_opacity"],
            k["social_icons"]) == ("r4c1", "r3c0", 150, 60, ["tiktok", "instagram"])
    # old names are still accepted and stored as grid cells
    k = client.patch(f"/api/brand-kits/{k['id']}", json={"logo_position": "bottom-right"}).json()
    assert k["logo_position"] == "r5c2"
    for bad in ("somewhere", "r6c0", "r0c3"):
        assert client.patch(f"/api/brand-kits/{k['id']}", json={"watermark_position": bad}).status_code == 422
        assert client.patch(f"/api/brand-kits/{k['id']}", json={"logo_position": bad}).status_code == 422
    assert client.patch(f"/api/brand-kits/{k['id']}", json={"watermark_size": 1000}).status_code == 422
    assert client.patch(f"/api/brand-kits/{k['id']}", json={"social_icons": ["myspace"]}).status_code == 422

    r = client.get("/api/watermark/preview", params={"text": "@grace", "icons": "tiktok,instagram", "size": 150})
    assert r.status_code == 200 and r.headers["content-type"] == "image/png"
    assert Image.open(io.BytesIO(r.content)).mode == "RGBA"
    assert client.get("/api/watermark/preview", params={"icons": "myspace"}).status_code == 400
    assert client.get("/api/watermark/preview").status_code == 400  # nothing to draw


def test_migration_upgrades_existing_database(tmp_path, monkeypatch):
    """A database created before watermark settings existed gets the new columns, keeping its data."""
    dbfile = tmp_path / "old.db"
    con = sqlite3.connect(dbfile)
    con.executescript("""
        CREATE TABLE schema_version (version INTEGER PRIMARY KEY, applied_at DATETIME);
        INSERT INTO schema_version VALUES (1, '2026-11-01');
        CREATE TABLE organizations (id VARCHAR(36) PRIMARY KEY, created_at DATETIME, updated_at DATETIME,
            name VARCHAR(200), speaker_name VARCHAR(200), onboarded BOOLEAN, platforms JSON);
        INSERT INTO organizations VALUES ('o1', '2026-11-01', '2026-11-01', 'Grace', NULL, 1, '[]');
        CREATE TABLE brand_kits (id VARCHAR(36) PRIMARY KEY, created_at DATETIME, updated_at DATETIME,
            org_id VARCHAR(36), name VARCHAR(200), logo_path VARCHAR(500), colors JSON, font VARCHAR(100),
            watermark_text VARCHAR(200), logo_position VARCHAR(20), default_template_id VARCHAR(36),
            is_default BOOLEAN, auto_apply BOOLEAN);
        INSERT INTO brand_kits VALUES ('k1', '2026-11-01', '2026-11-01', 'o1', 'Grace', NULL, '{}', NULL,
            '@grace', 'top-right', NULL, 1, 1);
        CREATE TABLE generated_clips (id VARCHAR(36) PRIMARY KEY, options JSON);
        INSERT INTO generated_clips VALUES ('c1', '{"captions": true, "wm_position": "bottom-center", "wm_size": 120}');
        INSERT INTO generated_clips VALUES ('c2', '{"captions": true, "wm_position": null}');
    """)
    con.commit()
    con.close()
    monkeypatch.setenv("DATA_DIR", str(tmp_path))
    from app import config, db
    config.get_settings.cache_clear()
    db.init_engine(f"sqlite:///{dbfile.as_posix()}")
    from app.migrations import migrate
    migrate()
    migrate()  # running twice is harmless
    db.engine().dispose()
    con = sqlite3.connect(dbfile)
    row = con.execute("select watermark_text, watermark_position, logo_position, watermark_size, watermark_opacity, "
                      "social_icons from brand_kits where id='k1'").fetchone()
    clips = dict(con.execute("select id, options from generated_clips"))
    versions = [v for (v,) in con.execute("select version from schema_version order by version")]
    con.close()
    config.get_settings.cache_clear()
    # v2 added the columns, v3 moved the old named positions onto the grid
    assert row == ("@grace", "r0c0", "r0c2", 100, 80, "[]")
    import json
    assert json.loads(clips["c1"]) == {"captions": True, "wm_position": "r5c1", "wm_size": 120}
    assert json.loads(clips["c2"])["wm_position"] is None  # "use the brand kit" left alone
    assert versions == [1, 2, 3]
